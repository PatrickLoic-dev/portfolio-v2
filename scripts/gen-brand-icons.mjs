/**
 * Regenerates src/components/brand-icon.tsx from simple-icons (CC0) and,
 * for LinkedIn (not in simple-icons), bootstrap-icons (MIT).
 *   node scripts/gen-brand-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import * as si from "simple-icons";

const fromSimple = (icon) => ({ viewBox: "0 0 24 24", paths: [icon.path], title: icon.title, hex: `#${icon.hex}` });
const fromBootstrap = (name, title, hex) => {
  const svg = readFileSync(`node_modules/bootstrap-icons/icons/${name}.svg`, "utf8");
  return { viewBox: /viewBox="([^"]+)"/.exec(svg)[1], paths: [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]), title, hex };
};

const icons = {
  linkedin: fromBootstrap("linkedin", "LinkedIn", "#0A66C2"),
  x: fromSimple(si.siX),
  instagram: fromSimple(si.siInstagram),
  steam: fromSimple(si.siSteam),
  spotify: fromSimple(si.siSpotify),
  applemusic: fromSimple(si.siApplemusic),
  github: fromSimple(si.siGithub),
  angular: fromSimple(si.siAngular),
  react: fromSimple(si.siReact),
  nestjs: fromSimple(si.siNestjs),
  docker: fromSimple(si.siDocker),
  nextdotjs: fromSimple(si.siNextdotjs),
  ionic: fromSimple(si.siIonic),
  postgresql: fromSimple(si.siPostgresql),
  javascript: fromSimple(si.siJavascript),
  typescript: fromSimple(si.siTypescript),
  tailwindcss: fromSimple(si.siTailwindcss),
  redux: fromSimple(si.siRedux),
  sass: fromSimple(si.siSass),
  stencil: fromSimple(si.siStencil),
  nodedotjs: fromSimple(si.siNodedotjs),
  mongodb: fromSimple(si.siMongodb),
  mysql: fromSimple(si.siMysql),
  git: fromSimple(si.siGit),
  notion: fromSimple(si.siNotion),
};

const out = `// Generated by scripts/gen-brand-icons.mjs — brand marks from simple-icons (CC0) and bootstrap-icons (MIT).
import type { SVGProps } from "react";

const ICONS = ${JSON.stringify(icons, null, 2)} as const;

export type Brand = keyof typeof ICONS;

/** Official brand glyph (single colour: currentColor). Decorative unless \`title\` is given. */
export function BrandIcon({ brand, size = 16, title, ...rest }: { brand: Brand; size?: number; title?: string } & SVGProps<SVGSVGElement>) {
  const icon = ICONS[brand];
  return (
    <svg
      viewBox={icon.viewBox}
      width={size}
      height={size}
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      {...rest}
    >
      {icon.paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}

/** Official brand colour (#RRGGBB), e.g. for hover states. */
export const brandColor = (brand: Brand): string => ICONS[brand].hex;
`;
writeFileSync("src/components/brand-icon.tsx", out);
console.log("✓", Object.keys(icons).join(", "));
